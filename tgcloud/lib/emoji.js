export const emojiId = (name) => EMOJI[name]?.[0];

// Вставка в текст (подходит и для rich HTML, и для обычного HTML).
export const em = (name) => {
  const e = EMOJI[name];
  return e ? `<tg-emoji emoji-id="${e[0]}">${e[1]}</tg-emoji>` : '';
};
export const emId = (id, fallback = '⭐️') => `<tg-emoji emoji-id="${id}">${fallback}</tg-emoji>`;

// Для fallback: убрать кастомные эмодзи, оставив обычные символы.
export const stripEmoji = (html) =>
  String(html).replace(/<tg-emoji[^>]*>([^<]*)<\/tg-emoji>/g, '$1');
